#!/usr/bin/env python3
"""Generate the repeatable Flyway migration R__food_images.sql from the exported food photos.

Usage (from tools/food-image):
    python make_migration.py                       # reads ../../frontend/public/foods/manifest.json
    python make_migration.py --manifest PATH       # another manifest

Input: the manifest written by the review tool ("Xuất tất cả"):
    {"foods": [{"food": "Ức gà", "slug": "uc-ga",
                "images": [{"file": "uc-ga/boiled-01.webp", "preparation": "BOILED",
                            "primary": true, "source": null}, ...]}, ...]}
Images are listed main photo first, then each preparation in pick order.

Output: backend/src/main/resources/db/migration/R__food_images.sql, which in one transaction
replaces every row of food_images with the manifest's photos.

Why a repeatable migration (R__) instead of a new V<n> each time: Flyway re-runs an R__ file
whenever its content changes, after all versioned migrations. Picking new photos = run this
script again and deploy; no new version number, and the file always holds the full current set.

Rows are found by (name, preparation), never by id: ids differ between databases.
A photo whose food row does not exist fails the whole migration, so nothing half-applies.
"""
import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
PUBLIC = ROOT / "frontend" / "public"
DEFAULT_MANIFEST = PUBLIC / "foods" / "manifest.json"
OUT = ROOT / "backend" / "src" / "main" / "resources" / "db" / "migration" / "R__food_images.sql"

# The photos were collected from Google Images: the original author and license are unknown.
CREDIT = "Google"
LICENSE = "Chưa rõ"

PREPARATIONS = {"RAW", "BOILED", "STEAMED", "FRIED", "BRAISED", "GRILLED"}
# Same wording as PREPARATION_LABELS in frontend/src/constants/meal.ts
LABELS = {"BOILED": "luộc", "STEAMED": "hấp", "FRIED": "chiên", "BRAISED": "kho", "GRILLED": "nướng"}
PATH_RE = re.compile(r"^foods/[a-z0-9-]+/[a-z0-9-]+\.webp$")  # same as ck_food_images_path (V23)


def nfc(text: str) -> str:
    """Vietnamese text can be stored composed or decomposed; the database uses composed (NFC)."""
    return unicodedata.normalize("NFC", text).strip()


def sql(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def source_url(source) -> str | None:
    """Photos exported with a {"url": ...} source keep their link; dropped-in files have none."""
    if isinstance(source, dict):
        url = source.get("url")
        if isinstance(url, str) and url.startswith(("https://", "http://")):
            return url
    return None


def build_rows(manifest: dict) -> tuple[list[dict], list[str]]:
    rows, errors, seen_paths = [], [], set()
    for food in manifest.get("foods", []):
        name = nfc(food["food"])
        next_order: dict[str, int] = {}
        for image in food.get("images", []):
            prep = image.get("preparation")
            path = "foods/" + image.get("file", "")
            where = f"{name} / {image.get('file')}"
            if prep not in PREPARATIONS:
                errors.append(f"{where}: unknown preparation {prep!r}")
                continue
            if not PATH_RE.fullmatch(path):
                errors.append(f"{where}: path does not match {PATH_RE.pattern}")
                continue
            if path in seen_paths:
                errors.append(f"{where}: listed twice")
                continue
            if not (PUBLIC / path).is_file():
                errors.append(f"{where}: file missing in frontend/public")
                continue
            seen_paths.add(path)

            # sort_order restarts per food row; the first photo of a row (0) is that row's main photo.
            # The manifest lists the food's main photo first, so it gets 0 in its own row.
            order = next_order.get(prep, 0)
            next_order[prep] = order + 1
            alt = f"Ảnh {name} {LABELS[prep]}" if prep in LABELS else f"Ảnh {name}"
            rows.append({
                "name": name, "preparation": prep, "path": path, "alt": alt[:200],
                "credit": CREDIT, "license": LICENSE,
                "source_url": source_url(image.get("source")), "sort_order": order,
            })
    return rows, errors


def render(rows: list[dict]) -> str:
    foods = len({(r["name"], r["preparation"]) for r in rows})
    out = [
        "-- Generated by tools/food-image/make_migration.py from frontend/public/foods/manifest.json.",
        "-- Do not hand-edit: re-export the photos with the review tool and regenerate.",
        "-- Repeatable migration: Flyway re-runs it whenever this file changes.",
        f"-- {len(rows)} photos for {foods} food rows.",
        "",
        "CREATE TEMP TABLE food_image_seed (",
        "    name TEXT, preparation TEXT, path TEXT, alt TEXT,",
        "    credit TEXT, license TEXT, source_url TEXT, sort_order SMALLINT",
        ") ON COMMIT DROP;",
        "",
    ]
    if rows:
        values = ",\n".join(
            "    (" + ", ".join(sql(r[k]) for k in (
                "name", "preparation", "path", "alt", "credit", "license", "source_url", "sort_order")) + ")"
            for r in rows
        )
        out += ["INSERT INTO food_image_seed VALUES", values + ";", ""]
    out += [
        "-- Every photo must belong to an existing food row, otherwise nothing is applied.",
        "DO $$",
        "DECLARE",
        "    missing TEXT;",
        "BEGIN",
        "    SELECT string_agg(DISTINCT s.name || ' (' || s.preparation || ')', ', ')",
        "    INTO missing",
        "    FROM food_image_seed s",
        "    LEFT JOIN foods f ON f.name = s.name AND f.preparation = s.preparation",
        "    WHERE f.id IS NULL;",
        "    IF missing IS NOT NULL THEN",
        "        RAISE EXCEPTION 'food_images: no foods row for %', missing;",
        "    END IF;",
        "END $$;",
        "",
        "DELETE FROM food_images;",
        "",
        "INSERT INTO food_images (food_id, path, alt, credit, license, source_url, sort_order)",
        "SELECT f.id, s.path, s.alt, s.credit, s.license, s.source_url, s.sort_order",
        "FROM food_image_seed s",
        "JOIN foods f ON f.name = s.name AND f.preparation = s.preparation;",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    args = ap.parse_args()

    if not args.manifest.is_file():
        sys.exit(f"Manifest not found: {args.manifest}\nExport the photos first (review tool, --out frontend/public/foods).")
    rows, errors = build_rows(json.loads(args.manifest.read_text(encoding="utf-8")))
    if errors:
        print("Not written, fix these first:", *errors, sep="\n  ", file=sys.stderr)
        sys.exit(1)

    OUT.write_text(render(rows), encoding="utf-8", newline="\n")
    foods = len({(r["name"], r["preparation"]) for r in rows})
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(rows)} photos for {foods} food rows.")


if __name__ == "__main__":
    main()
