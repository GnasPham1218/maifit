#!/usr/bin/env python3
"""Generate V17__food_source_descriptions.sql: the original USDA name of every food row.

Usage (from tools/usda-import):  python3 make_source_descriptions.py

Why: the food detail page shows which USDA item the numbers come from ("Tên gốc"). Until now that
name only lived in the "--" comment at the end of each INSERT line, which never reaches the database.

Where each description comes from:
  1. SR Legacy rows: food.csv of the SR Legacy download (data/), looked up by the FDC id in `source`.
     Exact text, nothing typed by hand.
  2. Foundation rows: that download has no food.csv, so the migration comment is used (the comment
     was copied from USDA when the row was written).
Rows whose comment starts with "XẤP XỈ" are flagged source_approximate: USDA has no exact match for
that Vietnamese food, the closest item is used. ƯỚC TÍNH rows (computed from two USDA items) keep a
NULL description; the app labels them from `source`.

Flyway checks file checksums, so V5/V7/V10 are never edited: this writes a new migration instead.
"""
import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIG_DIR = HERE.parent.parent / "backend" / "src" / "main" / "resources" / "db" / "migration"
SR_FOOD_CSV = next((HERE / "data" / "sr_legacy").glob("*/food.csv"), None)
SOURCE_FILES = ["V5__seed_foods.sql", "V7__more_foods.sql", "V10__pork_rib_cuts.sql"]
OUT = MIG_DIR / "V17__food_source_descriptions.sql"

# ('Name', 'PREP', kcal, ..., 'source')  -- comment
ROW = re.compile(r"^\('((?:[^']|'')+)',\s*'([A-Z]+)',.*,\s*'((?:[^']|'')+)'\)[,;]\s*(?:--\s*(.*))?$")
FDC = re.compile(r"^USDA FDC (\d+) \((SR Legacy|Foundation)\)$")


def sql(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def load_sr_descriptions() -> dict[str, str]:
    if SR_FOOD_CSV is None:
        sys.exit("SR Legacy food.csv not found under data/sr_legacy/ (download it first, see README)")
    with SR_FOOD_CSV.open(encoding="utf-8", newline="") as f:
        return {r["fdc_id"]: r["description"].strip() for r in csv.DictReader(f)}


def main() -> None:
    sr = load_sr_descriptions()
    descriptions: dict[str, str] = {}  # source -> description (one FDC item can back several rows)
    approximate: list[tuple[str, str]] = []  # (name, preparation)
    problems: list[str] = []

    for file in SOURCE_FILES:
        for line_no, line in enumerate((MIG_DIR / file).read_text(encoding="utf-8").splitlines(), 1):
            m = ROW.match(line.strip())
            if not m:
                continue
            name, prep, source, comment = m.group(1), m.group(2), m.group(3), (m.group(4) or "").strip()
            if comment.upper().startswith("XẤP XỈ"):
                approximate.append((name, prep))
            fdc = FDC.match(source)
            if not fdc:
                continue  # ƯỚC TÍNH or a non-USDA source: no single original item
            fdc_id, dataset = fdc.groups()
            if dataset == "SR Legacy":
                text = sr.get(fdc_id)
                if text is None:
                    problems.append(f"{file}:{line_no} FDC {fdc_id} not in SR Legacy food.csv")
                    continue
            else:
                # Strip our own prefix/notes; a "..." comment is an abbreviation, not the USDA text
                text = re.sub(r"^XẤP XỈ:\s*", "", comment)
                if not text or text.startswith("..."):
                    problems.append(f"{file}:{line_no} Foundation row without a usable comment")
                    continue
            if source in descriptions and descriptions[source] != text:
                problems.append(f"{file}:{line_no} {source} has two different descriptions")
            descriptions[source] = text

    if problems:
        sys.exit("Fix these first:\n  " + "\n  ".join(problems))

    seed = ",\n".join(f"    ({sql(s)}, {sql(d)})" for s, d in sorted(descriptions.items()))
    approx = ",\n".join(f"    ({sql(n)}, {sql(p)})" for n, p in approximate)
    OUT.write_text(f"""-- The original USDA item behind each food row, for the food detail page ("Tên gốc").
-- Generated by tools/usda-import/make_source_descriptions.py: SR Legacy names come from USDA's food.csv,
-- Foundation names from the migration comments. Do not hand-edit; regenerate.
-- New foods migrations (V18+) write source_description / source_approximate in their own INSERT.

ALTER TABLE foods
    ADD COLUMN source_description TEXT,
    ADD COLUMN source_approximate BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN foods.source_description IS 'Original name of the source item, e.g. the USDA description. NULL for estimated rows';
COMMENT ON COLUMN foods.source_approximate IS 'TRUE when the source has no exact match and the closest item is used (XẤP XỈ)';

CREATE TEMP TABLE description_seed (source TEXT PRIMARY KEY, description TEXT NOT NULL) ON COMMIT DROP;
INSERT INTO description_seed VALUES
{seed};

CREATE TEMP TABLE approximate_seed (name TEXT, preparation TEXT) ON COMMIT DROP;
INSERT INTO approximate_seed VALUES
{approx};

-- Fail the migration rather than write half of it: every seed row must match a food
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM description_seed s WHERE NOT EXISTS (SELECT 1 FROM foods f WHERE f.source = s.source)) THEN
        RAISE EXCEPTION 'description_seed has a source that no food uses';
    END IF;
    IF EXISTS (SELECT 1 FROM approximate_seed s
               WHERE NOT EXISTS (SELECT 1 FROM foods f WHERE f.name = s.name AND f.preparation = s.preparation)) THEN
        RAISE EXCEPTION 'approximate_seed has a (name, preparation) that does not exist';
    END IF;
END $$;

UPDATE foods f SET source_description = s.description FROM description_seed s WHERE f.source = s.source;
UPDATE foods f SET source_approximate = TRUE FROM approximate_seed s
WHERE f.name = s.name AND f.preparation = s.preparation;

-- And every single-item USDA row must now have its description
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM foods WHERE source ~ '^USDA FDC [0-9]+ \\(' AND source_description IS NULL) THEN
        RAISE EXCEPTION 'a USDA food row is still without source_description';
    END IF;
END $$;
""", encoding="utf-8", newline="\r\n")  # CRLF like the other migrations
    print(f"Wrote {OUT.name}: {len(descriptions)} sources, {len(approximate)} approximate rows")


if __name__ == "__main__":
    main()
