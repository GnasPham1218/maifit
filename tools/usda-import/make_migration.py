#!/usr/bin/env python3
"""Generate V7__more_foods.sql and V8__more_food_aliases.sql from the reviewed review.csv.

Usage (from tools/usda-import):  python3 make_migration.py

Why a script: every number is copied from the USDA file, never typed by hand, and the
checks below fail fast BEFORE Flyway would fail halfway through a migration.
"""
import csv
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIG_DIR = HERE.parent.parent / "backend" / "src" / "main" / "resources" / "db" / "migration"
REVIEW = HERE / "review.csv"

KCAL_MAX = 1000  # raised from 900 in V4: lard is 902 kcal/100 g


def fold(s: str) -> str:
    """lower + remove accents (đ -> d), same idea as f_unaccent(lower(x)) in Postgres."""
    s = s.lower().replace("đ", "d")
    s = unicodedata.normalize("NFD", s)
    return "".join(c for c in s if unicodedata.category(c) != "Mn").strip()


def sql(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def num(s: str, places: int) -> str:
    return "NULL" if s.strip() == "" else f"{float(s):.{places}f}"


def existing_state():
    """Names/fdc ids from V5 and aliases from V6, so V7/V8 cannot collide with them."""
    v5 = (MIG_DIR / "V5__seed_foods.sql").read_text(encoding="utf-8")
    names = set(re.findall(r"^\('([^']+)',\s*'([A-Z]+)'", v5, re.M))
    fdc = set(re.findall(r"USDA FDC (\d+)", v5))
    v6 = (MIG_DIR / "V6__food_search.sql").read_text(encoding="utf-8")
    aliases = {fold(a) for a in re.findall(r"^\s*\('[^']+',\s*'[A-Z]+',\s*'([^']+)',\s*(?:TRUE|FALSE)\)", v6, re.M)}
    return names, fdc, aliases


def main() -> int:
    rows = [r for r in csv.DictReader(open(REVIEW, encoding="utf-8-sig", newline="")) if r["use"].strip() == "1"]
    old_names, old_fdc, old_aliases = existing_state()
    errors, warnings = [], []

    seen_pair, seen_fdc = set(), set()
    for r in rows:
        key = (r["viet_name"].strip(), r["preparation"].strip())
        if key in seen_pair:
            errors.append(f"duplicate (name, preparation) in CSV: {key}")
        if key in old_names:
            errors.append(f"already in V5: {key}")
        seen_pair.add(key)
        if r["fdc_id"] in old_fdc:
            errors.append(f"fdc {r['fdc_id']} already in V5 ({key})")
        # the same fdc id twice is allowed only when it is intentional (two names, same item); warn
        if r["fdc_id"] in seen_fdc:
            warnings.append(f"fdc {r['fdc_id']} used more than once ({key})")
        seen_fdc.add(r["fdc_id"])
        if not r["kcal"] or float(r["kcal"]) > KCAL_MAX:
            errors.append(f"kcal out of range: {key} {r['kcal']}")
        for col in ("protein_g", "carb_g", "fat_g", "fiber_g"):
            if r[col] and not 0 <= float(r[col]) <= 100:
                errors.append(f"{col} out of range: {key} {r[col]}")
        if r["preparation"] not in ("RAW", "BOILED", "STEAMED", "FRIED", "BRAISED", "GRILLED"):
            errors.append(f"bad preparation: {key}")

    # Foods are compared accent-insensitively too: "Cải bẹ xanh" vs "Cai be xanh" would confuse the matcher
    all_names = {fold(n): n for n, _ in old_names}
    for r in rows:
        f = fold(r["viet_name"])
        owner = all_names.setdefault(f, r["viet_name"])
        if owner != r["viet_name"]:
            errors.append(f"names collide after unaccent: {r['viet_name']!r} vs {owner!r}")

    # ---- V7: foods
    lines = [
        "-- More foods imported from USDA FoodData Central (SR Legacy, CC0).",
        "-- Generated by tools/usda-import/make_migration.py from the reviewed review.csv. Do not hand-edit numbers:",
        "-- change the CSV, regenerate, and (before the first deploy) replace this file.",
        "-- Same conventions as V5: values per 100 g, NULL = no data, comment = original USDA description.",
        "",
        "-- V4 capped kcal at 900, but lard is 902 kcal/100 g (USDA FDC 171401). 1000 still blocks typos.",
        "ALTER TABLE foods DROP CONSTRAINT ck_foods_kcal;",
        "ALTER TABLE foods ADD CONSTRAINT ck_foods_kcal CHECK (kcal BETWEEN 0 AND 1000);",
        "",
        "INSERT INTO foods (name, preparation, kcal, protein_g, carb_g, fat_g, fiber_g, source) VALUES",
    ]
    last_group = None
    for i, r in enumerate(rows):
        if r["group"] != last_group:
            lines.append(f"-- ===== {r['group']} =====")
            last_group = r["group"]
        desc = r["usda_description"].replace("\n", " ")
        src = f"USDA FDC {r['fdc_id']} (SR Legacy)"
        end = ";" if i == len(rows) - 1 else ","
        # the "--" comment must come after the comma/semicolon, otherwise the comma is swallowed
        lines.append(
            f"({sql(r['viet_name'])+',':<27} {sql(r['preparation'])+',':<10} {num(r['kcal'], 1):>6}, "
            f"{num(r['protein_g'], 2):>6}, {num(r['carb_g'], 2):>6}, {num(r['fat_g'], 2):>6}, "
            f"{num(r['fiber_g'], 2):>5}, {sql(src)}){end} -- {desc}"
        )
    v7 = "\n".join(lines) + "\n"

    # ---- V8: aliases. One alias = one food row. Put it on the RAW row (or the only row of that name).
    by_name = {}
    for r in rows:
        by_name.setdefault(r["viet_name"], []).append(r)
    taken = set(old_aliases)
    taken_names = set(all_names)
    alias_rows = []
    for name, group in by_name.items():
        target = next((g for g in group if g["preparation"] == "RAW"), group[0])
        for a in [x.strip() for x in target["aliases"].split("|") if x.strip()]:
            fa = fold(a)
            if fa in taken:
                warnings.append(f"alias skipped (already an alias): {a!r} -> {name}")
            elif fa in taken_names and a.lower() == all_names[fa].lower():
                warnings.append(f"alias skipped (equals a food name): {a!r} -> {name}")
            elif fa == fold(name) and a.lower() == name.lower():
                continue
            else:
                taken.add(fa)
                alias_rows.append((name, target["preparation"], a))

    v8 = [
        "-- Everyday names for the foods added in V7 (see V6 for how aliases work).",
        "-- Aliases sit on the RAW row of a food; the matcher picks BOILED/FRIED... from the AI's preparation.",
        "",
        "CREATE TEMP TABLE alias_seed (name TEXT, preparation TEXT, alias TEXT) ON COMMIT DROP;",
        "INSERT INTO alias_seed VALUES",
    ]
    for i, (n, p, a) in enumerate(alias_rows):
        end = ";" if i == len(alias_rows) - 1 else ","
        v8.append(f"    ({sql(n)}, {sql(p)}, {sql(a)}){end}")
    v8 += [
        "",
        "-- Fail loudly if an alias points to a food that does not exist",
        "DO $$",
        "DECLARE missing TEXT;",
        "BEGIN",
        "    SELECT string_agg(s.alias, ', ') INTO missing",
        "    FROM alias_seed s",
        "    LEFT JOIN foods f ON f.name = s.name AND f.preparation = s.preparation",
        "    WHERE f.id IS NULL;",
        "    IF missing IS NOT NULL THEN",
        "        RAISE EXCEPTION 'food_aliases seed: no foods row for %', missing;",
        "    END IF;",
        "END $$;",
        "",
        "INSERT INTO food_aliases (food_id, alias, locks_preparation)",
        "SELECT f.id, s.alias, FALSE",
        "FROM alias_seed s",
        "JOIN foods f ON f.name = s.name AND f.preparation = s.preparation;",
    ]

    for w in warnings:
        print("WARN ", w)
    for e in errors:
        print("ERROR", e)
    if errors:
        print(f"\n{len(errors)} error(s): nothing written.")
        return 1

    (MIG_DIR / "V7__more_foods.sql").write_text(v7, encoding="utf-8", newline="\n")
    (MIG_DIR / "V8__more_food_aliases.sql").write_text("\n".join(v8) + "\n", encoding="utf-8", newline="\n")
    print(f"OK: {len(rows)} foods ({len(by_name)} names), {len(alias_rows)} aliases, {len(warnings)} warnings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
